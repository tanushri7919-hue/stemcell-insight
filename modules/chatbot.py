def render_chatbot():
    st.markdown("## 💬 Ask StemCell Insight – Biology Chatbot")
    st.markdown(
        "Ask questions about stem cell types, potency, differentiation pathways, molecular markers, "
        "signaling cascades, and experimental protocols. Responses are grounded in curated peer-reviewed literature."
    )

    # Disclaimer banner
    st.markdown(
        """
        <div style="background: #f0fdf4; border: 1px solid #bbf7d0; border-left: 4px solid #16a34a; border-radius: 6px; padding: 0.8rem 1rem; margin-bottom: 1.2rem; font-size: 0.88rem; color: #166534;">
            <b>Scientific Evidence Guardrail:</b> Answers are derived strictly from our curated database. If an answer cannot be substantiated by verified literature records, the chatbot will explicitly inform you rather than extrapolating.
        </div>
        """,
        unsafe_allow_html=True
    )

    # Initialize chat history in session state
    if "chat_history" not in st.session_state:
        st.session_state.chat_history = [
            {
                "role": "assistant",
                "content": (
                    "Hello! I am **StemCell Insight Assistant**, your biological knowledge guide. "
                    "You can ask me about stem-cell categories (ESCs, iPSCs, MSCs, HSCs, NSCs), "
                    "differentiation mechanisms, key transcription factors, or experimental conditions. "
                    "How can I help you today?"
                ),
                "references": []
            }
        ]

    # Quick prompt buttons
    st.markdown("**💡 Suggested Questions:**")
    q_cols = st.columns(3)
    clicked_question = None

    for i, q in enumerate(SUGGESTED_QUESTIONS[:6]):
        with q_cols[i % 3]:
            if st.button(q, key=f"sq_{i}", use_container_width=True):
                clicked_question = q

    # Display chat history
    for msg in st.session_state.chat_history:
        with st.chat_message(msg["role"]):
            st.markdown(msg["content"])
            if msg.get("references"):
                with st.expander("📚 Supporting Scientific References", expanded=False):
                    for ref in msg["references"]:
                        doi_link = f" [DOI: {ref.get('DOI')}](https://doi.org/{ref.get('DOI')})" if ref.get('DOI') else ""
                        st.markdown(f"- **{ref.get('title')}** ({ref.get('authors', 'Unknown')}, *{ref.get('journal', 'Journal')}*, {ref.get('publication_year', '')}).{doi_link}")

    # User Input Field
    user_input = st.chat_input("Enter your biology question here...")
    active_prompt = clicked_question or user_input

    if active_prompt:
        # Add user query to chat history
        st.session_state.chat_history.append({"role": "user", "content": active_prompt})
        with st.chat_message("user"):
            st.markdown(active_prompt)

        # Generate response using retrieval engine
        with st.chat_message("assistant"):
            with st.spinner("Searching biological knowledge base..."):
                response_text, references = answer_question(active_prompt)
                st.markdown(response_text)
                if references:
                    with st.expander("📚 Supporting Scientific References", expanded=False):
                        for ref in references:
                            doi_link = f" [DOI: {ref.get('DOI')}](https://doi.org/{ref.get('DOI')})" if ref.get('DOI') else ""
                            st.markdown(f"- **{ref.get('title')}** ({ref.get('authors', 'Unknown')}, *{ref.get('journal', 'Journal')}*, {ref.get('publication_year', '')}).{doi_link}")

        # Store in session state
        st.session_state.chat_history.append({
            "role": "assistant",
            "content": response_text,
            "references": references
        })


def answer_question(query: str) -> (str, List[Dict[str, Any]]):
    """Core retrieval logic that maps queries to biological entities and builds
    factual, evidence-backed responses with traceable literature citations.
    """
    clean_q = query.lower().strip()
    expanded_terms = expand_query_terms(query)
    results = search_all_entities(query)

    # 1. Check for Comparison: ESCs vs iPSCs
    if ("difference" in clean_q or "compare" in clean_q or "vs" in clean_q) and (
        ("esc" in clean_q or "embryonic" in clean_q or "esc" in expanded_terms) and
        ("ipsc" in clean_q or "induced" in clean_q or "ipsc" in expanded_terms)
    ):
        return _format_esc_vs_ipsc_response()

    # 2. Check for MSC differentiation capabilities
    if "msc" in expanded_terms and ("differentiat" in clean_q or "capabilit" in clean_q or "lineage" in clean_q or "fate" in clean_q):
        return _format_msc_capabilities_response()

    # 3. Check for Osteogenic differentiation / markers
    if "osteo" in clean_q:
        return _format_osteogenesis_response(results)

    # 4. Check for Adipogenic differentiation / markers
    if "adipo" in clean_q or "fat" in clean_q:
        return _format_adipogenesis_response(results)

    # 5. Check for Chondrogenic differentiation / cartilage
    if "chondro" in clean_q or "cartilage" in clean_q:
        return _format_chondrogenesis_response(results)

    # 6. Check for BMP signaling
    if "bmp" in expanded_terms or "bone morphogenetic" in clean_q:
        return _format_bmp_signaling_response(results)

    # 7. Check for HSC / Hematopoietic lineages
    if "hsc" in expanded_terms or "hematopoietic" in clean_q or "blood" in clean_q:
        return _format_hsc_lineages_response(results)

    # 8. Check for NSC / Neural stem cell capabilities
    if "nsc" in expanded_terms or "neural stem" in clean_q:
        return _format_nsc_capabilities_response(results)

    # 9. Check for Pluripotent characteristics
    if "pluripotent" in clean_q or "pluripotency" in clean_q:
        return _format_pluripotency_response(results)

    # 10. Check for Dual SMAD inhibition
    if "dual smad" in clean_q or "smad inhibition" in clean_q or ("neural" in clean_q and "conversion" in clean_q):
        return _format_dual_smad_response(results)

    # 11. General Entity Matching fallback
    if any(len(lst) > 0 for lst in results.values()):
        return _format_general_entity_response(query, results)

    # Out of Domain safeguard
    return (
        "This information is not currently available in the curated StemCell Insight knowledge base.\n\n"
        "Try asking about:\n"
        "- The 5 primary stem-cell types (ESCs, iPSCs, MSCs, HSCs, NSCs)\n"
        "- Specific differentiation lineages (osteogenesis, adipogenesis, chondrogenesis, neural conversion, cardiogenesis)\n"
        "- Signaling cascades (BMP, Wnt, TGF-β, Dual SMAD inhibition)\n"
        "- Molecular markers (OCT4, SOX2, CD73, RUNX2, PPARγ, TNNT2)",
        []
    )


