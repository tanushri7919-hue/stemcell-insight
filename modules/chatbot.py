    if results.get("markers"):
        parts.append("\n#### Molecular Markers:")
        for m in results["markers"][:4]:
            parts.append(f"- **{m.get('gene_symbol') or m.get('marker_name')}** ({m.get('marker_type', 'Marker')}): {m.get('description')}")

    if results.get("signals"):
        parts.append("\n#### Signaling Molecules & Pathways:")
        for s in results["signals"][:3]:
            parts.append(f"- **{s.get('signal_name')}** ({s.get('pathway')}): {s.get('effect')}")

    if results.get("protocols"):
        parts.append("\n#### Published Protocols:")
        for p in results["protocols"][:2]:
            parts.append(f"- **{p.get('protocol_name')}:** {p.get('source_cell')} ➔ {p.get('target_cell')}. Duration: {p.get('duration')}. Efficiency: {p.get('reported_efficiency')}")
            if p.get("ref_doi"):
                refs.append({"title": p.get("protocol_name"), "authors": "Published Protocol", "journal": "Curated Literature", "publication_year": "", "DOI": p.get("ref_doi")})

    if results.get("references"):
        for r in results["references"][:3]:
            refs.append(r)

    return "\n".join(parts), refs
